#!/usr/bin/env python3
"""Render the objectives from con-site-specific's records.

Two outputs.  By default, the front page's cards.  The front page is a theme
template, not a page under content/pages/, so this writes an include for
theme/templates/index.html to pull in.  It holds the same itembox rows as
"Our principles" above it: a description's first paragraph (what we do)
takes the plain <p>, the paragraphs after it (the problem it addresses) take
<p class="pitch">.

Which objectives, and in which order, is the site root's `influenced_by` --
the same list, with the same filter, as the store's own homepage template.

With --page, content/pages/objectives.html: each objective in full, followed
by the projects that name it in their own `influenced_by`, linked the way
whoweare links them -- to the project's entry on the projects page when it
has one, to its own site otherwise.
"""
import argparse
import html
import re
import sys

from conrecords import RECORDS, load_yaml, toc_hook, write_page
from render_projects import logo_for
from render_whoweare import page_anchors

COLUMNS = 3
PREFIX = "xyzrins:objectives/"
# the one piece of Markdown the descriptions use
LINK = re.compile(r"\[([^\]]+)\]\((https?://[^)\s]+)\)")


def objectives():
    """The current objectives of the site root, and what could not be shown."""
    records = {}
    for f in sorted((RECORDS / "XYZObjective").glob("*.yaml")):
        d = load_yaml(f)
        records[d["pid"]] = d
    rows, skipped = [], []
    for inf in load_yaml(RECORDS / "XYZProject/site-root.yaml").get("influenced_by") or []:
        pid = inf["object"]
        if not pid.startswith(PREFIX) or inf.get("ended"):
            continue
        d = records.get(pid)
        if d is None:
            skipped.append((pid, "no such XYZObjective record"))
        elif not d.get("description"):
            skipped.append((pid, "no description"))
        else:
            rows.append(d)
    return rows, skipped


def inline(text):
    return LINK.sub(r'<a href="\2">\1</a>', html.escape(text.strip()))


def cell(d, offset):
    first, *rest = d["description"].strip().split("\n\n")
    out = [f'\t  <div class="col-md-4 col-sm-4{offset}">',
           '\t\t<div class="itembox-heading">',
           # the heading leads to the objective's section on the objectives page
           f'\t\t  <a href="/objectives#{toc_hook(d["title"])}">'
           f'<span>{html.escape(d["title"])}</span></a>',
           '\t\t</div>',
           f'\t\t<p>{inline(first)}</p>']
    out += [f'\t\t<p class="pitch">{inline(p)}</p>' for p in rest]
    out.append('\t  </div>')
    return out


def render():
    rows, skipped = objectives()
    out = ["{# Generated by scripts/render_objectives.py: edit the records, "
           "not this file. #}"]
    for i in range(0, len(rows), COLUMNS):
        chunk = rows[i:i + COLUMNS]
        # a short last row sits in the middle rather than against the left
        n = 2 * (COLUMNS - len(chunk))
        offset = f" col-md-offset-{n} col-sm-offset-{n}" if n else ""
        out += ['  <div class="itembox">', '\t<div class="row">']
        for j, d in enumerate(chunk):
            out += cell(d, offset if j == 0 else "")
        out += ['\t</div>', '  </div>']
    return "\n".join(out) + "\n", skipped


def grant_pages():
    """grant pid -> its page, for the grants that have one."""
    out = {}
    for f in sorted((RECORDS / "XYZGrant").glob("*.yaml")):
        d = load_yaml(f)
        page = homepage(d)
        if page:
            out[d["pid"]] = page
    return out


def homepage(d):
    return next((a["value"] for a in d.get("attributes") or []
                 if a.get("predicate") == "foaf:homepage"), None)


def projects_by_objective():
    """objective pid -> [(label, href or None, logo or None, note), ...].

    A project with neither an entry on the projects page nor a site of its
    own -- a collaboration where CON's part is advice and infrastructure
    support, not a product -- links to the page of the grant funding it, and
    its description becomes the tile's tooltip.
    """
    anchors, grants, out = page_anchors(), grant_pages(), {}
    for f in sorted((RECORDS / "XYZProject").glob("*.yaml")):
        d = load_yaml(f)
        if d["pid"] == "xyzrins:.":
            continue
        label = d.get("short_name") or d.get("display_label") or d.get("title") or f.stem
        href = anchors.get(d["pid"]) or homepage(d)
        note = None
        if not href:
            href = next((grants[i["object"]] for i in d.get("influenced_by") or []
                         if "FRAPO:Funding" in (i.get("roles") or [])
                         and i["object"] in grants), None)
            note = " ".join((d.get("description") or "").split()) or None
        for inf in d.get("influenced_by") or []:
            if inf["object"].startswith(PREFIX) and not inf.get("ended"):
                out.setdefault(inf["object"], []).append(
                    (label, href, logo_for(f.stem), note))
    return {k: sorted(v, key=lambda r: r[0].lower()) for k, v in out.items()}


def render_page():
    rows, skipped = objectives()
    projects = projects_by_objective()
    out = ['<html>', '', '<head>', '\t<title>Objectives</title>',
           '\t<meta name="url" content="objectives" />',
           '\t<meta name="save_as" content="objectives.html" />',
           # the menu has no room for an eighth item; the front page links here
           '\t<meta name="show_in_top_menu" content="false" />',
           # the menu sorts every page by it, shown or not
           '\t<meta name="order" content="9" />',
           '\t<meta name="show_as_selected" content="objectives" />',
           '\t<meta name="table_of_contents" content="true" />',
           '\t<meta name="description" content="What the center works toward, '
           'and the projects behind each objective" />',
           '\t<meta name="author" content="CON" />',
           '\t<!-- GENERATED from con-site-specific by scripts/render_objectives.py (page mode)',
           '\t     Edit the records, not this file. -->',
           '</head>', '', '<body>', '  <section>', '  <div id="objectives">']
    for d in rows:
        first, *rest = d["description"].strip().split("\n\n")
        out += [f'\t<h2>{html.escape(d["title"])}</h2>',
                f'\t<p>{inline(first)}</p>']
        out += [f'\t<p class="pitch">{inline(p)}</p>' for p in rest]
        mine = projects.get(d["pid"]) or []
        if not mine:
            continue
        out.append('\t<ul class="objective-projects">')
        for label, href, logo, note in mine:
            img = f'<img src="{html.escape(logo)}" alt="" />' if logo else ''
            name = f'{img}<span>{html.escape(label)}</span>'
            if href:
                tip = f' title="{html.escape(note)}"' if note else ''
                name = f'<a href="{html.escape(href)}"{tip}>{name}</a>'
            out.append(f'\t  <li>{name}</li>')
        out.append('\t</ul>')
    out += ['  </div>', '  </section>', '</body>', '', '</html>']
    return "\n".join(out) + "\n", skipped


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--out")
    ap.add_argument("--page", action="store_true",
                    help="render the objectives page instead of the front page's cards")
    a = ap.parse_args()
    markup, skipped = (render_page if a.page else render)()
    for pid, why in skipped:
        print(f"SKIPPED {pid}: {why}", file=sys.stderr)
    return write_page(markup, a.out, skipped)


if __name__ == "__main__":
    sys.exit(main())
